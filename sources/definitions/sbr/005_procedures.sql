-- -----------------------------------------------------------------------------
-- SBR_DETECT_SCHEMA_GAPS: Detects schema drift in vendor files
-- -----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SBR_DETECT_SCHEMA_GAPS(P_VENDOR_ID VARCHAR, P_FILE_NAME VARCHAR, P_COLUMNS_JSON VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
    V_VENDOR_NAME VARCHAR;
BEGIN
    SELECT VENDOR_NAME INTO V_VENDOR_NAME FROM DEMO_DEV.SBR_ANALYTICS.GOLD_DIM_VENDOR WHERE VENDOR_ID = :P_VENDOR_ID;

    INSERT INTO DEMO_DEV.SBR_ANALYTICS.SILVER_VENDOR_FILE_LOG (VENDOR_ID, VENDOR_NAME, FILE_NAME, FILE_PATH, COLUMNS_FOUND, COLUMN_COUNT, ROW_COUNT, SCHEMA_MATCH_STATUS)
    SELECT :P_VENDOR_ID, :V_VENDOR_NAME, :P_FILE_NAME,
           '@SBR_SOURCE_STAGE/' || :P_VENDOR_ID || '/' || :P_FILE_NAME,
           TRY_PARSE_JSON(:P_COLUMNS_JSON), ARRAY_SIZE(TRY_PARSE_JSON(:P_COLUMNS_JSON)), 0, 'PENDING';

    INSERT INTO DEMO_DEV.SBR_ANALYTICS.SILVER_SCHEMA_GAPS (VENDOR_ID, VENDOR_NAME, FILE_NAME, GAP_TYPE, COLUMN_NAME, EXPECTED_VALUE, SEVERITY, DESCRIPTION)
    SELECT :P_VENDOR_ID, :V_VENDOR_NAME, :P_FILE_NAME, 'MISSING_COLUMN', r.COLUMN_NAME, r.COLUMN_NAME, 'HIGH',
           'Expected column ' || r.COLUMN_NAME || ' not found in file'
    FROM DEMO_DEV.SBR_ANALYTICS.SILVER_SCHEMA_REGISTRY r
    WHERE r.VENDOR_ID = :P_VENDOR_ID
      AND r.COLUMN_NAME NOT IN (SELECT VALUE::VARCHAR FROM TABLE(FLATTEN(TRY_PARSE_JSON(:P_COLUMNS_JSON))));

    RETURN 'GAPS_DETECTED';
END
$$;

-- -----------------------------------------------------------------------------
-- SBR_AUDIT_METRICS_AGENT: Runs audit metrics collection
-- -----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SBR_AUDIT_METRICS_AGENT()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
    V_TOTAL_BRZ NUMBER;
    V_TOTAL_SLV NUMBER;
    V_TOTAL_GLD NUMBER;
    V_SCHEMA_GAPS NUMBER;
    V_OPEN_CASES NUMBER;
    V_TOTAL_VARIANCE NUMBER;
    V_AUDIT_JSON VARCHAR;
BEGIN
    SELECT COUNT(*) INTO V_TOTAL_BRZ FROM DEMO_DEV.SBR_ANALYTICS.BRONZE_LABOR;
    SELECT COUNT(*) INTO V_TOTAL_SLV FROM DEMO_DEV.SBR_ANALYTICS.SILVER_LABOR;
    SELECT COUNT(*) INTO V_TOTAL_GLD FROM DEMO_DEV.SBR_ANALYTICS.GOLD_FACT_LABOR;
    SELECT COUNT(*) INTO V_SCHEMA_GAPS FROM DEMO_DEV.SBR_ANALYTICS.SILVER_SCHEMA_GAPS WHERE STATUS = 'OPEN';
    SELECT COUNT(*) INTO V_OPEN_CASES FROM DEMO_DEV.SBR_ANALYTICS.GOLD_APP_SBR_CASES WHERE STATUS = 'OPEN';
    SELECT COALESCE(SUM(ABS(VARIANCE)), 0) INTO V_TOTAL_VARIANCE FROM DEMO_DEV.SBR_ANALYTICS.GOLD_FACT_LABOR;

    V_AUDIT_JSON := '{"bronze_records":' || :V_TOTAL_BRZ ||
                    ',"silver_records":' || :V_TOTAL_SLV ||
                    ',"gold_records":' || :V_TOTAL_GLD ||
                    ',"open_schema_gaps":' || :V_SCHEMA_GAPS ||
                    ',"open_cases":' || :V_OPEN_CASES ||
                    ',"total_abs_variance":' || :V_TOTAL_VARIANCE || '}';

    INSERT INTO DEMO_DEV.SBR_ANALYTICS.SILVER_AUDIT_METRICS (BATCH_ID, TOTAL_RECORDS, FAILED_RECORDS, TOTAL_VARIANCE)
    SELECT 'AUDIT_AGENT_' || TO_VARCHAR(CURRENT_TIMESTAMP(), 'YYYYMMDD_HH24MISS'),
           :V_TOTAL_GLD,
           :V_TOTAL_GLD - :V_TOTAL_SLV,
           :V_TOTAL_VARIANCE;

    RETURN V_AUDIT_JSON;
END
$$;
