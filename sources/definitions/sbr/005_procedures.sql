-- -----------------------------------------------------------------------------
-- SBR_CREATE_CASE: Creates a new investigation case
-- -----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SBR_CREATE_CASE(P_EMP_ID VARCHAR, P_PERIOD_START DATE, P_PERIOD_END DATE, P_SEVERITY VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
    V_CASE_ID VARCHAR;
    V_USER VARCHAR;
    V_ROLE VARCHAR;
    V_PAYLOAD VARCHAR;
BEGIN
    V_CASE_ID := UUID_STRING();
    V_USER := CURRENT_USER();
    V_ROLE := CURRENT_ROLE();
    V_PAYLOAD := '{"emp_id":"' || :P_EMP_ID || '","severity":"' || :P_SEVERITY || '"}';
    INSERT INTO DEMO_DEV.SBR_ANALYTICS.GOLD_APP_SBR_CASES (CASE_ID, EMP_ID, PERIOD_START, PERIOD_END, STATUS, SEVERITY, CREATED_BY, UPDATED_BY)
    VALUES (:V_CASE_ID, :P_EMP_ID, :P_PERIOD_START, :P_PERIOD_END, 'OPEN', :P_SEVERITY, :V_USER, :V_USER);
    INSERT INTO DEMO_DEV.SBR_ANALYTICS.GOLD_APP_SBR_CASE_EVENTS (CASE_ID, EVENT_TYPE, USER_NAME, USER_ROLE, PAYLOAD)
    SELECT :V_CASE_ID, 'CREATE_CASE', :V_USER, :V_ROLE, PARSE_JSON(:V_PAYLOAD);
    RETURN V_CASE_ID;
END
$$;

-- -----------------------------------------------------------------------------
-- SBR_UPDATE_CASE: Updates case status and logs event
-- -----------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE SBR_UPDATE_CASE(P_CASE_ID VARCHAR, P_EVENT_TYPE VARCHAR, P_PAYLOAD VARCHAR)
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS
$$
DECLARE
    V_USER VARCHAR;
    V_ROLE VARCHAR;
BEGIN
    V_USER := CURRENT_USER();
    V_ROLE := CURRENT_ROLE();
    IF (:P_EVENT_TYPE = 'STATUS_CHANGE') THEN
        UPDATE DEMO_DEV.SBR_ANALYTICS.GOLD_APP_SBR_CASES
        SET STATUS = PARSE_JSON(:P_PAYLOAD):status::VARCHAR,
            UPDATED_AT = CURRENT_TIMESTAMP(),
            UPDATED_BY = :V_USER
        WHERE CASE_ID = :P_CASE_ID;
    END IF;
    INSERT INTO DEMO_DEV.SBR_ANALYTICS.GOLD_APP_SBR_CASE_EVENTS (CASE_ID, EVENT_TYPE, USER_NAME, USER_ROLE, PAYLOAD)
    SELECT :P_CASE_ID, :P_EVENT_TYPE, :V_USER, :V_ROLE, TRY_PARSE_JSON(:P_PAYLOAD);
    RETURN 'OK';
END
$$;

