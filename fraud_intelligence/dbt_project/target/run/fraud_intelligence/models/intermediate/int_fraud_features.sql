
  
    

        create or replace transient table DEMO_DEV.FRAUD_INTELLIGENCE.SLV_FRAUD_FEATURES
         as
        (

SELECT
    t.TRANSACTION_ID,
    t.CUSTOMER_ID,
    t.TRANSACTION_AMOUNT,
    t.TRANSACTION_TYPE,
    t.MERCHANT_CATEGORY,
    t.CHANNEL,
    DATEDIFF(DAY, c.CUSTOMER_SINCE, t.TRANSACTION_DATE) AS ACCOUNT_AGE_DAYS,
    t.TRANSACTION_AMOUNT * 10 AS CREDIT_LIMIT,
    t.TRANSACTION_AMOUNT * 3 AS CURRENT_BALANCE,
    COALESCE(t.ACCOUNT_ID, 'UNKNOWN') AS ACCOUNT_TYPE,
    CASE
        WHEN t.TRANSACTION_AMOUNT * 10 > 0
            THEN ROUND((t.TRANSACTION_AMOUNT * 3) / (t.TRANSACTION_AMOUNT * 10), 4)
        ELSE 0
    END AS UTILIZATION_RATIO,
    c.RISK_SEGMENT,
    c.KYC_COMPLETE,
    0 AS ADDRESS_CHANGE_COUNT,
    c.IS_SYNTHETIC_FLAG,
    c.IS_MERGER_DUP_FLAG,
    c.CUSTOMER_TENURE_DAYS,
    COALESCE(alert_counts.PRIOR_ALERT_COUNT, 0) AS PRIOR_ALERT_COUNT_CUSTOMER,
    COALESCE(alert_7d.ALERT_WITHIN_7D, 0) AS ALERT_WITHIN_7D,
    COALESCE(v.TXN_COUNT_1H, 0) AS TXN_COUNT_1H,
    COALESCE(v.TXN_COUNT_24H, 0) AS TXN_COUNT_24H,
    COALESCE(v.TXN_AMOUNT_1H, 0) AS TXN_AMOUNT_1H,
    COALESCE(v.TXN_AMOUNT_24H, 0) AS TXN_AMOUNT_24H,
    COALESCE(v.DISTINCT_MERCHANTS_24H, 0) AS DISTINCT_MERCHANTS_24H
FROM DEMO_DEV.FRAUD_INTELLIGENCE.stg_raw_transactions t
LEFT JOIN DEMO_DEV.FRAUD_INTELLIGENCE.stg_raw_customers c
    ON t.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN (
    SELECT CUSTOMER_ID, MAX(TXN_COUNT_1H) AS TXN_COUNT_1H, MAX(TXN_COUNT_24H) AS TXN_COUNT_24H,
           MAX(TXN_AMOUNT_1H) AS TXN_AMOUNT_1H, MAX(TXN_AMOUNT_24H) AS TXN_AMOUNT_24H,
           MAX(DISTINCT_MERCHANTS_24H) AS DISTINCT_MERCHANTS_24H
    FROM DEMO_DEV.FRAUD_INTELLIGENCE.stg_raw_velocity_events
    GROUP BY CUSTOMER_ID
) v ON t.CUSTOMER_ID = v.CUSTOMER_ID
LEFT JOIN (
    SELECT CUSTOMER_ID, COUNT(*) AS PRIOR_ALERT_COUNT
    FROM DEMO_DEV.FRAUD_INTELLIGENCE.stg_raw_alerts
    GROUP BY CUSTOMER_ID
) alert_counts ON t.CUSTOMER_ID = alert_counts.CUSTOMER_ID
LEFT JOIN (
    SELECT CUSTOMER_ID, COUNT(*) AS ALERT_WITHIN_7D
    FROM DEMO_DEV.FRAUD_INTELLIGENCE.stg_raw_alerts
    WHERE ALERT_DATE >= DATEADD(DAY, -7, CURRENT_TIMESTAMP())
    GROUP BY CUSTOMER_ID
) alert_7d ON t.CUSTOMER_ID = alert_7d.CUSTOMER_ID
        );
      
  