
  
    

        create or replace transient table DEMO_DEV.FRAUD_INTELLIGENCE.GLD_ML_TRAINING_SET
         as
        (

WITH fraud_labels AS (
    SELECT DISTINCT
        ad.CUSTOMER_ID,
        ad.TRANSACTION_ID
    FROM DEMO_DEV.FRAUD_INTELLIGENCE.stg_analyst_decisions ad
    WHERE ad.DECISION = 'CONFIRMED_FRAUD'
),
alert_fraud_labels AS (
    SELECT DISTINCT
        a.CUSTOMER_ID
    FROM DEMO_DEV.FRAUD_INTELLIGENCE.stg_raw_alerts a
    WHERE a.DISPOSITION IN ('FRAUD_CONFIRMED', 'SAR_FILED', 'CONFIRMED_FRAUD')
       OR a.SAR_FILED = TRUE
)

SELECT
    f.TRANSACTION_ID,
    f.CUSTOMER_ID,
    f.ACCOUNT_TYPE AS ACCOUNT_ID,
    CURRENT_TIMESTAMP() AS TRANSACTION_DATE,
    f.TRANSACTION_AMOUNT,
    f.TRANSACTION_TYPE,
    f.MERCHANT_CATEGORY,
    f.CHANNEL,
    f.ACCOUNT_AGE_DAYS,
    f.CREDIT_LIMIT,
    f.CURRENT_BALANCE,
    f.ACCOUNT_TYPE,
    f.UTILIZATION_RATIO,
    f.RISK_SEGMENT,
    f.KYC_COMPLETE,
    f.ADDRESS_CHANGE_COUNT,
    f.IS_SYNTHETIC_FLAG,
    f.IS_MERGER_DUP_FLAG,
    f.CUSTOMER_TENURE_DAYS,
    f.PRIOR_ALERT_COUNT_CUSTOMER,
    f.ALERT_WITHIN_7D,
    f.TXN_COUNT_1H,
    f.TXN_COUNT_24H,
    f.TXN_AMOUNT_1H,
    f.TXN_AMOUNT_24H,
    f.DISTINCT_MERCHANTS_24H,
    CASE
        WHEN fl.TRANSACTION_ID IS NOT NULL THEN TRUE
        WHEN afl.CUSTOMER_ID IS NOT NULL THEN TRUE
        ELSE FALSE
    END AS TARGET_LABEL,
    CASE
        WHEN fl.TRANSACTION_ID IS NOT NULL THEN 'FRAUD'
        WHEN afl.CUSTOMER_ID IS NOT NULL THEN 'FRAUD'
        ELSE 'NON_FRAUD'
    END AS CLASS_LABEL,
    CASE
        WHEN MOD(ABS(HASH(f.TRANSACTION_ID)), 5) = 0 THEN 'FOLD_1'
        WHEN MOD(ABS(HASH(f.TRANSACTION_ID)), 5) = 1 THEN 'FOLD_2'
        WHEN MOD(ABS(HASH(f.TRANSACTION_ID)), 5) = 2 THEN 'FOLD_3'
        WHEN MOD(ABS(HASH(f.TRANSACTION_ID)), 5) = 3 THEN 'FOLD_4'
        ELSE 'FOLD_5'
    END AS STRATIFIED_FOLD,
    'BALANCED' AS CLASS_WEIGHT_STRATEGY,
    CURRENT_TIMESTAMP() AS DBT_LOADED_AT
FROM DEMO_DEV.FRAUD_INTELLIGENCE.SLV_FRAUD_FEATURES f
LEFT JOIN fraud_labels fl
    ON f.TRANSACTION_ID = fl.TRANSACTION_ID
LEFT JOIN alert_fraud_labels afl
    ON f.CUSTOMER_ID = afl.CUSTOMER_ID
        );
      
  