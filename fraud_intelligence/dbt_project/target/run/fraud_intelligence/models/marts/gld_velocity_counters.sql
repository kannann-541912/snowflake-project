
  
    

        create or replace transient table DEMO_DEV.FRAUD_INTELLIGENCE.GLD_VELOCITY_COUNTERS
         as
        (

SELECT
    v.CUSTOMER_ID,
    MAX(v.EVENT_TIMESTAMP) AS LAST_UPDATED,
    MAX(v.TXN_COUNT_1H) AS TXN_COUNT_1H,
    MAX(v.TXN_COUNT_24H) AS TXN_COUNT_24H,
    MAX(v.TXN_AMOUNT_1H) AS TXN_AMOUNT_1H,
    MAX(v.TXN_AMOUNT_24H) AS TXN_AMOUNT_24H,
    MAX(v.DISTINCT_MERCHANTS_24H) AS DISTINCT_MERCHANTS_24H,
    MAX(v.RECENT_TXN_COUNT) AS RECENT_TXN_COUNT,
    MAX(v.RECENT_TXN_AMOUNT) AS RECENT_TXN_AMOUNT,
    MAX(v.FRAUD_RATE_7D) AS FRAUD_RATE_7D
FROM DEMO_DEV.FRAUD_INTELLIGENCE.stg_raw_velocity_events v
GROUP BY v.CUSTOMER_ID
        );
      
  