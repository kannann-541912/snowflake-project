ALTER TABLE DEMO_DEV.FRAUD_INTELLIGENCE.SLV_INVESTIGATION_KNOWLEDGE_BASE SET TAG DATA_LAYER = 'SILVER';
ALTER TABLE DEMO_DEV.FRAUD_INTELLIGENCE.SLV_RULE_CODE_KNOWLEDGE_MAP SET TAG DATA_LAYER = 'SILVER';

