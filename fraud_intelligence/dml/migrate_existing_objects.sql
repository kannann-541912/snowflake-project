-- Step 1: Copy Gold-layer tables
CREATE OR REPLACE TABLE DEMO_DEV.FRAUD_INTELLIGENCE.GLD_ALERT_ENRICHED
    CLONE DEMO_DEV.GOLD.ALERT_ENRICHED;

CREATE OR REPLACE TABLE DEMO_DEV.FRAUD_INTELLIGENCE.GLD_ML_TRAINING_SET
    CLONE DEMO_DEV.GOLD.ML_TRAINING_SET;

-- Hybrid Tables cannot be cloned; use CTAS
CREATE OR REPLACE TABLE DEMO_DEV.FRAUD_INTELLIGENCE.GLD_CUSTOMER_PROFILE AS
    SELECT * FROM DEMO_DEV.GOLD.CUSTOMER_PROFILE;

CREATE OR REPLACE TABLE DEMO_DEV.FRAUD_INTELLIGENCE.GLD_VELOCITY_COUNTERS AS
    SELECT * FROM DEMO_DEV.GOLD.VELOCITY_COUNTERS;

-- Step 2: Copy Silver-layer tables
CREATE OR REPLACE TABLE DEMO_DEV.FRAUD_INTELLIGENCE.SLV_FRAUD_MODEL_METADATA
    CLONE DEMO_DEV.GOLD.FRAUD_MODEL_METADATA;

CREATE OR REPLACE TABLE DEMO_DEV.FRAUD_INTELLIGENCE.SLV_MODEL_PERFORMANCE_LOG
    CLONE DEMO_DEV.GOLD.MODEL_PERFORMANCE_LOG;

CREATE OR REPLACE TABLE DEMO_DEV.FRAUD_INTELLIGENCE.SLV_FRAUD_EVAL_DATA
    CLONE DEMO_DEV.GOLD.FRAUD_EVAL_DATA;

CREATE OR REPLACE TABLE DEMO_DEV.FRAUD_INTELLIGENCE.SLV_INVESTIGATION_KNOWLEDGE_BASE
    CLONE DEMO_DEV.GOLD.INVESTIGATION_KNOWLEDGE_BASE;

CREATE OR REPLACE TABLE DEMO_DEV.FRAUD_INTELLIGENCE.SLV_RULE_CODE_KNOWLEDGE_MAP
    CLONE DEMO_DEV.GOLD.RULE_CODE_KNOWLEDGE_MAP;

-- Step 3: Recreate views in new schema with renamed references
